// Generates precache.js (file list + content-hash version) for the service worker.
// Run before deploying:  npm run build
// Refuses to proceed if anything that looks like personal data is inside pwa/ (this folder gets hosted).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXCLUDE_DIRS = new Set(["node_modules", "tests", "tools", ".git"]);
const EXCLUDE_FILES = new Set(["package.json", "package-lock.json", ".gitignore", "precache.js", "sw.js", "README.md"]);
const SUSPICIOUS = /\.(zip|out|err|tmp|bak|sqlite|db)$|(backup|export|data)[^/]*\.json$/i;

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) { if (!EXCLUDE_DIRS.has(name)) walk(full); continue; }
    if (EXCLUDE_FILES.has(name) || name.startsWith(".")) continue;  // hidden files (.nojekyll, .gitignore) aren't app files
    const rel = relative(root, full).split(sep).join("/");
    if (SUSPICIOUS.test(rel) && !rel.endsWith(".LICENSE")) {
      console.error(`Refusing to build: "${rel}" looks like a backup/data file inside the hosted folder.`);
      process.exit(1);
    }
    files.push(rel);
  }
})(root);
files.sort();

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest("hex").slice(0, 12);

writeFileSync(join(root, "precache.js"),
  `// GENERATED by tools/build.mjs - do not edit.\nself.__PRECACHE = ${JSON.stringify({ version, files: ["./", ...files] }, null, 2)};\n`);
const bytes = files.reduce((n, f) => n + statSync(join(root, f)).size, 0);
console.log(`precache.js: ${files.length} files, ${(bytes / 1e6).toFixed(2)} MB, version ${version}`);
